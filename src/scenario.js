//            stream: true … 検索中に、ログが高速で流れる演出（変更ログなど）
//            entries[].before / after … その結果を出す前／師匠が話したあとに流れる演出（台本。初めてのときだけ）
//              台本では { auto: "コマンド" }（プレイヤーが手早く打った体で、自動で流れる）、{ flash: true }（赤く光って警告音）も使える
