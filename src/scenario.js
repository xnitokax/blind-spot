//  ■ 任務（chapter）の書き方
//    code:  回線コード。uzu 側で師匠がプレイヤーに渡す。タイトル画面で connect <コード> と打つとその任務が始まる
//           （?line=コード 付きの URL で開いても始まる）
//           ※ ビルドすると任務のデータ全体がこのコードで暗号化される
//    date / clock: 画面右上の日付と、開始時刻
//    route: 回線をつなぐときに経由する中継点（移動の演出）
//    intro: 接続したあとに流れるセリフ（goal の script と同じ書き方ができる）
//           { music: true } で師匠が BGM を流し始める（エピローグは師匠がいないので流さない）
//    noise: true で、ときどき「送信エラー」のログが一瞬出る（兄のプログラムの伏線）
//           noiseStop のノードを訪れると止まる
//    start: 最初のノード
//    objective: 任務開始のカードに出る「目的」
//    objectives: 任務の中の小さな目標（右の欄に黄色の枠で出る）。上から順に1つずつ進む
//           { text, clues: [手がかりの名前...], until: { opened: ノードid } | { visited: ノードid } | { clue: 手がかりの名前 } | { goal: true } }
//           until を満たすと「OBJECTIVE CLEAR」→ 次の目標へ。clues は、その目標のための手がかり（n / N で数える）
//           ready: [セリフ] … その目標の手がかりが全部そろったときに、師匠が一度だけ話す（次にやることの案内）
//           intro: [セリフ] … その目標が始まったとき（NEXT OBJECTIVE のカードのあと）に、師匠が話す（どこを探すかの案内）
//           side: true の目標は、本筋とは別の「気になること」として、いつも一番下に出る
//    cardLabel: 任務開始のカードの見出し（省略すると MISSION。目的がない章は LOG）
//    practice: true … 練習の章（終わると、タイトル画面で練習を勧めなくなる）
//    demo: true … 体験版に入れる章。tools/build.html で「体験版」にチェックを入れてビルドすると、
//           公開データ（scenario.data.js）には demo の章だけが入り、ほかは scenario.more.js に分かれる
//           scenario.more.js は、タイトル画面で connect nitoka と打つと読み込まれる（続きが遊べるようになる）
//
//  ■ チュートリアル（SCENARIO.training）… 練習の章の回線コード。初めての人に、師匠が「connect training」と案内する
//
//  ■ 全体の目標（SCENARIO.caseGoal）… 右の欄のいちばん上に、ずっと出る（例：兄の死の真相に迫る）
//
//  ■ ノード（接続先）の書き方
//    host, title: 画面に出るアドレスと名前
//    body:   本文（HTML）。<a data-go="ノードid">…</a> で接続先になる（ssh 名前 で移動）
//            data-oneway を付けると一方通行
//    say:    初めて来たときの師匠のセリフ（配列）。body に <!--say--> と書くと、本文のその位置で話す
//            ※ 師匠のセリフの「、」「。」は、画面では「, 」「. 」になる（師匠の話し方。ここでは普通に書いてよい）
//    clue:   初めて来たときに記録される「手がかり」の名前（画面右の EVIDENCE 欄に集まる）
//            search の entries[] と dir[] にも clue を付けられる。任務完了の画面に「回収 n/N」と出る
//    breach: ["文字", ...] … 初めて入るときに、守りの壁が崩れ、手順ごとのバーが埋まって ACCESS GRANTED になる演出（任務2）
//    zone:   "files" / "hr" / "seek" / "keiri" / "bank" / "jyoshi" … 入ると画面の色合いが変わる（docs/css/style.css の body[data-zone]）
//    bgm:    0〜3 … 入ると、ボーナスタイムの曲（"run"）の盛り上がりがそこまで上がる（下がらない。ループの終わりで切りかわる。3 はサビ）
//    need:   "flag" … 任務の nav（どこからでも行ける接続先）に、その flag が立つまでは出さない（台本の { flag } で立てる）
//    entry:  [台本] … 初めて入るときの、そのシステム専用の見せ場（breach の代わり。例：金庫のダイヤル）
//    scene:  [台本] … 初めて来て本文を出したあとに流れる見せ場（例：ファイルがあふれ出す）
//    actions: { "コマンド": { script: [台本], next } } … その場所でだけ使える特別なコマンド（例：scan / open ??????）
//            押すと台本が流れる（一度だけ）。終わったら next の「次の一手」を出す
//    react:  { "コマンド": { script: [台本], next } } … その場所でそのコマンド（ls / help / back など）を打ったあとに、
//            師匠が反応する（一度だけ）。コマンドはふつうに実行される（actions とちがって、置きかえない）。チュートリアル用
//    next:   { at: ノードid, cmd: "search 鷲尾" } … 師匠が言った「次の一手」。NEXT 欄の先頭に光るボタンで出て、押すと入力欄に入る（実行は Enter か ⏎ ボタン）
//            ノードの say のほか、search の entries[] / notes[]、dir[]、目標（objectives の intro と一緒に）、任務（導入のあと）に書ける
//            why … 光るボタンのすぐ上に出る「なぜそれをやるのか」（行動の理由。その場の基調の色の補色。短い説明文）
//            go  … まだその場所にいないとき（移動のボタンが光っているとき）に出す理由。なければ why
//    lock:   { pass: "パスワード" or [...], hint, prompt, penalty, say, showLength, user }
