//  uzu シナリオ：Web 側（ハッキング画面）のデータ
//  ⚠️ ネタバレそのものです（回線コードもパスワードも平文で入っています）
//  編集したら tools/build.html でビルドして docs/scenario.data.js を更新します。
//
//  設定は「設定メモ.md」が正。ここでは未定のところを（仮）で埋めています。
//  「（仮）」で検索すると、あとで決めるところが一覧できます。
// =========================================================
//
//  ■ プレイヤーのハンドル名
//    最初に師匠に聞かれて決める呼び名。セリフ・本文・タイトル・結末の文章に {handle} と書くと、その名前に置きかわる
//
//  ■ 任務（chapter）の書き方
//    code:  回線コード。uzu 側で師匠がプレイヤーに渡す。タイトル画面で connect <コード> と打つとその任務が始まる
//           （?line=コード 付きの URL で開いても始まる）
//           ※ ビルドすると任務のデータ全体がこのコードで暗号化される
//    date / clock: 画面右上の日付と、開始時刻
//    route: 回線をつなぐときに経由する中継点（移動の演出）
//    intro: 接続したあとに流れるセリフ（goal の script と同じ書き方ができる）
//           { music: true } で師匠が BGM を流し始める（エピローグは師匠がいないので流さない）
//    noise: true で、ときどき「送信エラー」のログが一瞬出る（兄のプログラムの伏線）
//           noiseStop のノードを訪れると止まる
//    start: 最初のノード
//    objective: 任務開始のカードに出る「目的」
//    objectives: 任務の中の小さな目標（右の欄に「▶ NOW」として出る）。上から順に1つずつ進む
//           { text, clues: [手がかりの名前...], until: { opened: ノードid } | { visited: ノードid } | { clue: 手がかりの名前 } | { goal: true } }
//           until を満たすと「OBJECTIVE CLEAR」→ 次の目標へ。clues は、その目標のための手がかり（n / N で数える）
//           side: true の目標は、本筋とは別の「気になること」として、いつも一番下に出る
//
//  ■ 全体の目標（SCENARIO.caseGoal）… 右の欄のいちばん上に、ずっと出る（例：兄の死の真相に迫る）
//
//  ■ ノード（接続先）の書き方
//    host, title: 画面に出るアドレスと名前
//    body:   本文（HTML）。<a data-go="ノードid">…</a> で接続先になる（ssh 名前 で移動）
//            data-oneway を付けると一方通行
//    say:    初めて来たときの師匠のセリフ（配列）
//    clue:   初めて来たときに記録される「手がかり」の名前（画面右の EVIDENCE 欄に集まる）
//            search の entries[] と dir[] にも clue を付けられる。任務完了の画面に「回収 n/N」と出る
//    lock:   { pass: "パスワード" or [...], hint, prompt, penalty, say, showLength, user }
//            pass は全角・半角、大文字・小文字、空白を区別しない
//            パスワードを間違えても入力画面のまま続けて打てる。何も入力せずに Enter / back / Esc で戻る
//            showLength: true でパスワードの文字数を見せる（入力中も [5/17] のように出る）
//            user: { prompt, hint, ids, owner, disabled } を付けると、先にユーザーIDを聞く（人事DB の書き方を参照）
//            ※ ビルドすると、host・title・lock 以外がこのパスワードで暗号化される
//    search: { label, limit, records, entries: [...], notes: [...], empty }
//            records は検索中の演出で回る「総件数」（見た目だけ）
//            totals: { 言葉: 件数 } … その言葉1つだけで検索したとき、結果の件数をこの数で表示する（見た目だけ）
//            　件数の少なさが手がかりになる検索（プロジェクト室 → 2件 など）には付けない
//            search <言葉> で entries を検索し、上から limit 件（既定 3 件）だけ表示する
//            スペース区切りで AND 検索。本文の文字と keys が検索対象
//            本文の中で class="nosearch" を付けた部分は検索に引っかからない
//            entries[].goal があると、その結果を見た時点で任務完了
//            entries[].say は、その結果が初めて表示されたときの師匠のセリフ
//            notes: { when: 言葉 or [...], say: [...] } … その言葉で検索したときの師匠のセリフ
//    dir:    [{ name, desc, text, alias, go, say }] … cd <名前> で移動するフォルダ
//            name で入ると text（中身）を表示。alias で入ると go に移動する
//    goal:   { script, tag, report } … このノードに来たら任務完了
//
//  ■ 任務完了（goal）
//    script: 演出の台本。文字列は1行ずつ表示（[師匠] で始まると師匠のセリフ、[!] で警告）
//            { wait: ミリ秒 } { glitch: true/false } { trace: 数値, ms } { ghost: "勝手に打たれる文字" }
//            { predict: [{ node, text, p }] } … 予測の一覧（node を訪れていれば一致 ✔）
//            { hex: 行数 } … データが流れる
//            { replay: true } … この任務でプレイヤーが打ったコマンドを「予測済」として流す
//            { eye: true or "文字" } … マウスを追いかける目が開く
//            { mode: "red" | "blue" | null } … 画面全体の色（red は警報とサイレン、blue は師匠が回線を奪い返した）
//            { spam: 行数 } … 逆探知のログが右の欄に流れ込む
//            { news: ["見出し", { meta, text }] } … ニュースが1件ずつ流れる
//            { corrupt: ミリ秒 } … 画面の文字がどんどん崩れていく
//            { sound: "boom" など } … 効果音（docs/index.html の SFX を参照）
//            { music: true / false } … 師匠の BGM を流す・止める
//            ※ mode: "red" で BGM はテープのように止まり、mode: "blue" で戻ってくる
//    tag:    完了画面の見出し
//    report: 完了画面の文章（uzu に持ち帰って師匠に報告する内容）
//    todo:   完了画面の最後に、別枠で目立たせる「次にやること」（例：uzu に戻って、師匠に報告してください。）
//    end:    "cut" にすると、画面が消える演出なしで、いきなり真っ暗になって終わる
