//      トークの書き方（docs/js/talk.js）：
//        { chat: { title, sub } } … 師匠との暗号チャットの画面にする ／ { meet: { place, time, portrait, who } } … 依頼人と会う場面にする（上に写真）
//        { who: "名前" } … 会う場面の写真の下の名前を変える（依頼人が名乗ったら、名前にする）
//        "[師匠] …"・"[しおり] …" … 相手のセリフ ／ "[自分] …" … 自分のセリフ（右の吹き出し）／ "[*] …" … システム ／ [] なし … 情景（ナレーション）
